export function nearestBoundary(lon: number, lat: number): { boundary: PlateBoundary; distanceKm: number } {
  const radiusKm = 6371
  const toRad = Math.PI / 180
  let best: { boundary: PlateBoundary; distanceKm: number } = { boundary: plateBoundaries[0], distanceKm: Number.POSITIVE_INFINITY }
  for (const boundary of plateBoundaries) {
    for (const [pointLon, pointLat] of boundary.path) {
      const dLat = (pointLat - lat) * toRad
      const dLon = (pointLon - lon) * toRad
      const meanLat = ((pointLat + lat) / 2) * toRad
      const x = dLon * Math.cos(meanLat)
      const distance = radiusKm * Math.sqrt(x * x + dLat * dLat)
      if (distance < best.distanceKm) best = { boundary, distanceKm: distance }
    }
  }
  return best
}
